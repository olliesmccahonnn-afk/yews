package com.itemskins;

import com.itemskins.SkinStore.Preset;
import com.itemskins.SkinStore.Skin;
import net.fabricmc.loader.api.FabricLoader;
import net.minecraft.util.Identifier;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.Comparator;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;
import java.util.stream.Stream;

/**
 * Writes a resource pack folder (resourcepacks/itemskins_generated) that contains:
 *  - an item definition + model + texture for every item in the active preset
 *  - a GUI sprite for every imported skin (used for previews in the mod's own GUI)
 *
 * The pack is enabled automatically by {@link SkinPack}, so the player never has to
 * touch the resource pack screen.
 */
public final class PackBuilder {
    public static final String PACK_DIR = "itemskins_generated";
    public static final String PACK_ID = "file/" + PACK_DIR;

    /** Resource pack format for 1.21.11. If a future/other version flags the pack as incompatible, change this. */
    private static final int PACK_FORMAT = 75;

    private static final String MCMETA = "{\"pack\":{\"pack_format\":" + PACK_FORMAT
            + ",\"min_format\":" + PACK_FORMAT + ",\"max_format\":" + PACK_FORMAT
            + ",\"description\":\"Generated by Item Skins - managed automatically\"}}";

    private PackBuilder() {}

    public static Path packRoot() {
        return FabricLoader.getInstance().getGameDir().resolve("resourcepacks").resolve(PACK_DIR);
    }

    public static synchronized void rebuild() {
        Path root = packRoot();
        try {
            deleteTree(root.resolve("assets"));
            Files.createDirectories(root);
            Files.writeString(root.resolve("pack.mcmeta"), MCMETA);

            // GUI preview sprites for every skin
            Path sprites = root.resolve("assets/itemskins/textures/gui/sprites/skin");
            Files.createDirectories(sprites);
            for (Skin s : SkinStore.data.skins) {
                copy(SkinStore.skinFile(s.id), sprites.resolve(s.id + ".png"));
            }

            if (!SkinStore.data.enabled) return;
            Preset preset = SkinStore.active();
            if (preset == null) return;

            Path textures = root.resolve("assets/itemskins/textures/item");
            Path models = root.resolve("assets/itemskins/models/item");
            Set<String> texWritten = new HashSet<>();
            Set<String> modelWritten = new HashSet<>();

            for (Map.Entry<String, String> e : preset.items.entrySet()) {
                Identifier item = Identifier.tryParse(e.getKey());
                Skin skin = SkinStore.findSkin(e.getValue());
                if (item == null || skin == null) continue;

                String kind = holdKind(item.getPath()); // "generated", "handheld", "handheld_rod", "handheld_mace"
                boolean flat = kind.equals("generated");
                String modelName = flat ? skin.id : kind + "/" + skin.id;

                if (texWritten.add(skin.id)) {
                    Files.createDirectories(textures);
                    copy(SkinStore.skinFile(skin.id), textures.resolve(skin.id + ".png"));
                }
                if (modelWritten.add(modelName)) {
                    Path modelFile = models.resolve(modelName + ".json");
                    Files.createDirectories(modelFile.getParent());
                    Files.writeString(modelFile,
                            "{\"parent\":\"minecraft:item/" + kind + "\",\"textures\":{\"layer0\":\"itemskins:item/"
                                    + skin.id + "\"}}");
                }

                Path def = root.resolve("assets").resolve(item.getNamespace()).resolve("items")
                        .resolve(item.getPath() + ".json");
                Files.createDirectories(def.getParent());
                Files.writeString(def,
                        "{\"model\":{\"type\":\"minecraft:model\",\"model\":\"itemskins:item/" + modelName + "\"}}");
            }
        } catch (IOException ex) {
            ItemSkinsClient.LOGGER.error("Could not build the Item Skins pack", ex);
        }
    }

    /** Picks the vanilla parent model so tools and weapons are held like normal. */
    private static String holdKind(String path) {
        if (path.equals("mace")) return "handheld_mace";
        if (path.equals("fishing_rod") || path.endsWith("_on_a_stick")) return "handheld_rod";
        if (path.endsWith("_sword") || path.endsWith("_axe") || path.endsWith("_pickaxe")
                || path.endsWith("_shovel") || path.endsWith("_hoe") || path.equals("stick")
                || path.equals("blaze_rod") || path.equals("breeze_rod") || path.equals("bone")) {
            return "handheld";
        }
        return "generated";
    }

    private static void copy(Path from, Path to) throws IOException {
        if (Files.exists(from)) Files.copy(from, to, StandardCopyOption.REPLACE_EXISTING);
    }

    private static void deleteTree(Path p) throws IOException {
        if (!Files.exists(p)) return;
        try (Stream<Path> walk = Files.walk(p)) {
            for (Path x : (Iterable<Path>) walk.sorted(Comparator.reverseOrder())::iterator) {
                Files.delete(x);
            }
        }
    }
}
